import { readFileSync } from 'node:fs';
import { defineConfig } from 'orval';
import { APPS, prepareSpec } from './scripts/prepare-spec.mjs';
import { SCHEMA_SOURCES } from './scripts/schema-sources.mjs';

// Generation is offline: every input is a committed schema file, never a
// running server. All sources are read here and merged by prepareSpec, so the
// first source is not a special case.
const loadSources = (): unknown[] =>
  SCHEMA_SOURCES.map((source: string) =>
    JSON.parse(readFileSync(new URL(`./${source}`, import.meta.url), 'utf8')),
  );

const app = (name: string) => ({
  input: {
    target: `./${SCHEMA_SOURCES[0]}`,
    // The schema addresses objects by href: a path may start with an href
    // parameter ("{task_href}"), which OpenAPI validation rejects.
    unsafeDisableValidation: true,
    override: {
      // Keeps one application, merges all sources and drops host-specific and
      // URL-format details before any code is generated.
      transformer: () => prepareSpec(loadSources(), name),
    },
  },
  output: {
    client: 'fetch' as const,
    namingConvention: 'kebab-case' as const,
    mode: 'tags' as const,
    target: `./src/${name}/${name}.ts`,
    schemas: {
      path: `./src/${name}/models`,
      splitByTags: true,
      type: 'zod' as const,
    },
    indexFiles: false,
    clean: true,
    override: {
      mutator: {
        path: './src/mutator/pulp-fetch.ts',
        name: 'pulpFetch',
      },
      // A multipart body may hold object-valued fields next to files; the
      // builder sends them as JSON text, which plain FormData would not.
      formData: {
        path: './src/mutator/form-data.ts',
        name: 'pulpFormData',
      },
      fetch: {
        includeHttpResponseReturnType: false,
      },
      // Plain ASCII on purpose: the default header carries a non-ASCII mark.
      header: (info: {
        title?: string;
        description?: string;
        version?: string;
      }) => [
        'Generated by orval',
        'Do not edit manually.',
        ...(info.title ? [info.title] : []),
        ...(info.description ? [info.description] : []),
        ...(info.version ? [`OpenAPI spec version: ${info.version}`] : []),
      ],
      zod: {
        generateReusableSchemas: true,
      },
    },
  },
});

export default defineConfig(
  Object.fromEntries(APPS.map((name: string) => [name, app(name)])),
);
